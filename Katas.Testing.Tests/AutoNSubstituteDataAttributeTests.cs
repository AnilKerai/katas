using NSubstitute;

namespace Katas.Testing.Tests;

public interface IGreeter
{
    string Greet(string name);
}

public class AutoNSubstituteDataAttributeTests
{
    [Theory, AutoNSubstituteData]
    public void AutoNSubstituteData_ShouldSupplySubstitute_WhenParameterIsInterface(
        IGreeter sub
        )
    {
        sub.Greet("Ada").Returns("Hello, Ada");

        sub.Greet("Ada").ShouldBe("Hello, Ada");
    }

    [Theory, AutoNSubstituteData]
    public void AutoNSubstituteData_ShouldSupplyRecordingSubstitute_WhenParameterIsInterface(
        IGreeter sub
        )
    {
        sub.Greet("Ada");

        sub.Received(1).Greet("Ada");
        sub.DidNotReceive().Greet("Bob");
    }

    [Theory, InlineAutoNSubstituteData("inline")]
    public void InlineAutoNSubstituteData_ShouldSupplyInlineValueAndSubstitute(
        string value,
        IGreeter sub
        )
    {
        value.ShouldBe("inline");

        sub.Greet(value).Returns("Hello, inline");

        sub.Greet(value).ShouldBe("Hello, inline");
    }

    [Theory, InlineAutoNSubstituteData("inline")]
    public void InlineAutoNSubstituteData_ShouldSupplyRecordingSubstitute_ForRemainingParameter(
        string value,
        IGreeter sub
        )
    {
        sub.Greet(value);

        sub.Received(1).Greet("inline");
        sub.DidNotReceive().Greet("other");
    }

    [Theory, InlineAutoNSubstituteData("first", 2)]
    public void InlineAutoNSubstituteData_ShouldSupplyInlineValuesInOrder_BeforeAutoGeneratedOnes(
        string first,
        int second,
        IGreeter sub
        )
    {
        first.ShouldBe("first");
        second.ShouldBe(2);

        sub.Greet(first).Returns("Hello, first");

        sub.Greet(first).ShouldBe("Hello, first");
    }
}
